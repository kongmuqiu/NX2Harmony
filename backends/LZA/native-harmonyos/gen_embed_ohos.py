# Generate the signed guest library sources (libtotk_guest.so) from the HarmonyOS rewrite: HarmonyOS executes code only
# from signed files, so the rewritten modules are linked into a library instead of being mapped at run time (the Android
# loader) - the iOS design (games/totk/ios/tools/gen_embed.py), with ELF sections instead of Mach-O segments and no remap:
# a linker script puts each module's three parts at their original offsets from the module base, so the library mapping
# is the module.
#   x0  [0, page_up(TEXT_END))        r-x  text with the game patches applied (tools/export_text.c for main)
#   w   [page_up(TEXT_END), PATCH_OFF) rw-  rodata, data, bss, key page (copy-on-write; the loader seals rodata / key R)
#   x1  [PATCH_OFF, page_up(size))     r-x  the rewriter's patch area
#   tail (main only) 16 KiB rw- zero page after the image (real-time frame step, render size)
# Every part's SHA-256 goes into the descriptor the runtime checks at load (runtime/loader.c, TOTK_OHOS map_module).
# Output is game material (incbin of the images): it stays under prepared/, never committed or published.
# usage: python gen_embed_ohos.py <rewritten dir> <x0 dir> <out dir>
import hashlib, json, sys
from pathlib import Path

PG = 0x4000
MODULES = ('main', 'sdk')   # Pokémon Legends: Z-A (runtime/loader.c NM under TOTK_GAME_ZA)
def up(n): return (n + PG - 1) & ~(PG - 1)
def sha(b): return hashlib.sha256(b).hexdigest()

rewritten, x0dir, out = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve(), Path(sys.argv[3]).resolve()
out.mkdir(parents=True, exist_ok=True)
report = json.loads((rewritten / 'phase12-validation.json').read_text())
asm = ['// Generated by native-harmonyos/gen_embed_ohos.py from the locally verified HarmonyOS rewrite. Do not publish.']
ld = ['SECTIONS {']
desc = ['/* Generated by native-harmonyos/gen_embed_ohos.py. */', '#include <stdint.h>',
        'typedef struct { char name[16]; const uint8_t *base, *w, *x1, *tail; uint64_t x0_size, w_size, x1_size, tail_size; '
        'char dx0[65], dw[65], dx1[65], dimage[65]; } TotkGuestModule;']
entries, manifest = [], {}
for name in MODULES:
    image = rewritten / f'{name}.patched.bin'
    data = image.read_bytes()
    assert sha(data) == report['module_file_sha256'][f'rewritten/{name}.patched.bin'], f'{name}: image is not the validated rewrite'
    hdr = dict(l[2:].split() for l in (rewritten / f'{name}.fixups.tsv').read_text().splitlines())
    text_end, patch, key = int(hdr['TEXT_END'], 16), int(hdr['PATCH_OFF'], 16), int(hdr['KEY_PAGE_OFF'], 16)
    x0, x1 = up(text_end), up(len(data))
    assert patch % PG == 0 and key % PG == 0 and x0 <= key and key + PG <= patch <= len(data), f'{name}: layout'
    xfile = x0dir / f'{name}.x0.bin'
    text = xfile.read_bytes() if xfile.exists() else data[:x0]
    assert len(text) == x0, f'{name}: exported text is {len(text):#x} bytes, expected {x0:#x}'
    diff = sum(text[i:i + 4] != data[i:i + 4] for i in range(0, x0, 4))
    assert name == 'main' or diff == 0, f'{name}: only main carries game patches'
    tail = PG if name == 'main' else 0
    w_bytes, x1_bytes = data[x0:patch], data[patch:] + bytes(x1 - len(data))
    img = image.as_posix()
    xsrc = xfile.as_posix() if xfile.exists() else img
    asm += [f'.section .mng_{name}_x0,"ax",%progbits', '.p2align 14', f'.globl totk_guest_{name}_x0',
            f'.type totk_guest_{name}_x0,%object', f'totk_guest_{name}_x0:', f'.incbin "{xsrc}", 0, {x0}',
            f'.section .mng_{name}_w,"aw",%progbits', '.p2align 14', f'.globl totk_guest_{name}_w', f'totk_guest_{name}_w:',
            f'.incbin "{img}", {x0}, {patch - x0}',
            f'.section .mng_{name}_x1,"ax",%progbits', '.p2align 14', f'.globl totk_guest_{name}_x1', f'totk_guest_{name}_x1:',
            f'.incbin "{img}", {patch}, {len(data) - patch}']
    if x1 > len(data):
        asm.append(f'.zero {x1 - len(data)}')
    if tail:
        asm += [f'.section .mng_{name}_tail,"aw",%nobits', '.p2align 14', f'.globl totk_guest_{name}_tail', f'totk_guest_{name}_tail:',
                f'.zero {tail}']
    ld += [f'  .mng_{name}_x0 ALIGN(0x10000) : {{ KEEP(*(.mng_{name}_x0)) }}',
           f'  .mng_{name}_w (ADDR(.mng_{name}_x0) + {x0:#x}) : {{ KEEP(*(.mng_{name}_w)) }}',
           f'  .mng_{name}_x1 (ADDR(.mng_{name}_x0) + {patch:#x}) : {{ KEEP(*(.mng_{name}_x1)) }}']
    if tail:
        ld.append(f'  .mng_{name}_tail (ADDR(.mng_{name}_x0) + {x1:#x}) (NOLOAD) : {{ KEEP(*(.mng_{name}_tail)) }}')
    d = dict(x0=sha(text), w=sha(w_bytes), x1=sha(x1_bytes))
    desc.append(f'extern const uint8_t totk_guest_{name}_x0[], totk_guest_{name}_w[], totk_guest_{name}_x1[];')
    if tail:
        desc.append(f'extern uint8_t totk_guest_{name}_tail[];')
    entries.append(f'  {{"{name}", totk_guest_{name}_x0, totk_guest_{name}_w, totk_guest_{name}_x1, '
                   f'{f"totk_guest_{name}_tail" if tail else "0"}, {x0:#x}u, {patch - x0:#x}u, {x1 - patch:#x}u, {tail:#x}u, '
                   f'"{d["x0"]}", "{d["w"]}", "{d["x1"]}", "{sha(data)}"}}')
    manifest[name] = dict(x0=x0, w=patch - x0, x1=x1 - patch, tail=tail, patched_words=diff, sha256=d, image_sha256=sha(data))
    print(f'{name}: x0 {x0:#x} w {patch - x0:#x} x1 {x1 - patch:#x} tail {tail:#x} patched_words {diff}')
ld.append('} INSERT AFTER .text;')
desc += [f'__attribute__((visibility("default"))) const TotkGuestModule totk_guest_modules[{len(MODULES)}] = {{', ',\n'.join(entries), '};']
(out / 'guest_images.S').write_text('\n'.join(asm) + '\n')
(out / 'guest_layout.ld').write_text('\n'.join(ld) + '\n')
(out / 'guest_modules.c').write_text('\n'.join(desc) + '\n')
(out / 'guest-manifest.json').write_text(json.dumps(manifest, indent=1) + '\n')
