"""nvn_thunks.S for the NVN name table, in the Android port's portable form (runtime/asm_compat.h: FUNC / SYM / GLOBL /
PAGE / PAGEOFF / CSTRING, Mach-O and ELF), word for word what the reference's file holds for its 523 names, for any count:
each thunk counts its call (LSE stadd on its 16-byte nvn_slot entry) and jumps to the entry's implementation; then the
thunk table nvn_thunk, the name table nvn_names and the names. MacNativeGames' gen_protos.py (from seedds/nxnative, MIT)
writes the Mach-O spelling only; the Switch 2 names (NVN2, 739 with MacNativeGames main's names.txt) need this one.
    python gen_nvn_thunks.py <names.txt> <out nvn_thunks.S>"""
import sys

names = [l.strip() for l in open(sys.argv[1], encoding='utf-8') if l.strip()]
out = ['#include "../../../../runtime/asm_compat.h"',
       '// Generated by native-harmonyos/tools/gen_nvn_thunks.py (the reference\'s gen_protos.py form), do not edit by hand.',
       '// (Symbol and section spellings go through ../../../../runtime/asm_compat.h for Mach-O and ELF.)',
       '// Counting uses the LSE atomic stadd (ARMv8.1): the next line makes this file independent of the compiler\'s -mcpu baseline.',
       '    .arch_extension lse', '    .text', '    .p2align 2']
for i in range(len(names)):
    off = 16 * i
    assert off < 65536, 'mov immediate'
    out += [f'    FUNC(nvnth_{i})', f'SYM(nvnth_{i}):', '    adrp x16, PAGE(SYM(nvn_slot))', '    add x16, x16, PAGEOFF(SYM(nvn_slot))',
            f'    mov x17, #{off}', '    add x16, x16, x17', '    mov x17, #1', '    stadd x17, [x16]', '    ldr x17, [x16, #8]', '    br x17']
out += ['    .data', '    .p2align 3', '    GLOBL(nvn_thunk)', 'SYM(nvn_thunk):']
out += [f'    .quad SYM(nvnth_{i})' for i in range(len(names))]
out += ['    GLOBL(nvn_names)', 'SYM(nvn_names):']
out += [f'    .quad Ln{i}' for i in range(len(names))]
out += ['    CSTRING']
out += [f'Ln{i}: .asciz "{n}"' for i, n in enumerate(names)]
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(len(names), 'names ->', sys.argv[2])
